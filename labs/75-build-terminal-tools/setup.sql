-- Fixed read-only lookup: owner context resolves ORDERS inside this lab schema,
-- regardless of the agent REST session's current database. No arbitrary SQL or writes.
CREATE PROCEDURE LOOKUP_ORDER(ORDER_ID VARCHAR)
RETURNS VARIANT LANGUAGE SQL EXECUTE AS OWNER
AS $$
DECLARE RESULT VARIANT;
BEGIN
  SELECT COALESCE(
    ARRAY_AGG(OBJECT_CONSTRUCT_KEEP_NULL(
      'order_id', o.ORDER_ID, 'item', o.ITEM, 'status', o.ORDER_STATUS,
      'amount_usd', o.AMOUNT, 'ship_date', o.SHIP_DATE, 'support_note', o.SUPPORT_NOTE))[0],
    OBJECT_CONSTRUCT('found', FALSE, 'order_id', :ORDER_ID))
  INTO :RESULT FROM ORDERS o WHERE o.ORDER_ID = :ORDER_ID;
  RETURN RESULT;
END;
$$;
