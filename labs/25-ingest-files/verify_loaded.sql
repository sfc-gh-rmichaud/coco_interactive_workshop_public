SELECT 'CSV rows' AS CLAIM, 2000 AS EXPECTED, COUNT(*) AS ACTUAL FROM RAW_CSV
UNION ALL SELECT 'JSON rows',2000,COUNT(*) FROM RAW_JSON
UNION ALL SELECT 'XML documents',1,COUNT(*) FROM RAW_XML
UNION ALL SELECT 'HTML rows',2000,COUNT(*) FROM RAW_HTML
UNION ALL SELECT 'unique CSV IDs',2000,COUNT(DISTINCT ORDER_ID) FROM RAW_CSV
UNION ALL SELECT 'unique HTML IDs',2000,COUNT(DISTINCT ORDER_ID) FROM RAW_HTML
UNION ALL SELECT 'CSV amount',206820,SUM(TRY_TO_DECIMAL(AMOUNT_TEXT,12,2)) FROM RAW_CSV
UNION ALL SELECT 'HTML amount',206820,SUM(TRY_TO_DECIMAL(AMOUNT_TEXT,12,2)) FROM RAW_HTML
UNION ALL SELECT 'PDF rows: quality gate, not model guarantee',30,COUNT(*) FROM RAW_PDF_LINES
UNION ALL SELECT 'PDF amount: quality gate, not model guarantee',937.05,SUM(TRY_TO_DECIMAL(AMOUNT_TEXT,12,2)) FROM RAW_PDF_LINES;
-- Compare multisets, so equal totals or duplicate IDs cannot hide differences.
WITH sources AS (
 SELECT 'CSV' AS SOURCE,ORDER_ID,ITEM,AMOUNT_TEXT FROM RAW_CSV
 UNION ALL SELECT 'HTML',ORDER_ID,ITEM,AMOUNT_TEXT FROM RAW_HTML
 UNION ALL SELECT 'JSON',PAYLOAD:order_id::VARCHAR,PAYLOAD:item::VARCHAR,PAYLOAD:amount::VARCHAR FROM RAW_JSON
 UNION ALL
 SELECT 'XML',XMLGET(f.VALUE,'order_id'):"$"::VARCHAR,
   XMLGET(f.VALUE,'item'):"$"::VARCHAR,XMLGET(f.VALUE,'amount'):"$"::VARCHAR
 FROM RAW_XML r,LATERAL FLATTEN(INPUT=>r.PAYLOAD:"$") f WHERE f.VALUE:"@"::VARCHAR='order'
), cells AS (
 SELECT ORDER_ID,ITEM,AMOUNT_TEXT,COUNT_IF(SOURCE='CSV') AS CSV_N,
 COUNT_IF(SOURCE='HTML') AS HTML_N,COUNT_IF(SOURCE='JSON') AS JSON_N,
 COUNT_IF(SOURCE='XML') AS XML_N FROM sources GROUP BY ORDER_ID,ITEM,AMOUNT_TEXT
)
SELECT 'structured format cell/multiplicity differences' AS CLAIM,0 AS EXPECTED,
 COUNT(*) AS ACTUAL FROM cells WHERE CSV_N IS DISTINCT FROM 1 OR HTML_N IS DISTINCT FROM 1
 OR JSON_N IS DISTINCT FROM 1 OR XML_N IS DISTINCT FROM 1;
WITH subset AS (SELECT * FROM RAW_CSV WHERE ORDER_ID BETWEEN 'A00001' AND 'A00030')
SELECT 'PDF differences from matching CSV subset' AS CLAIM,0 AS EXPECTED,COUNT(*) AS ACTUAL
FROM subset c FULL JOIN RAW_PDF_LINES p ON c.ORDER_ID=p.ORDER_ID
WHERE c.ORDER_ID IS NULL OR p.ORDER_ID IS NULL OR c.ITEM IS DISTINCT FROM p.ITEM
 OR TRY_TO_DECIMAL(c.AMOUNT_TEXT,12,2) IS DISTINCT FROM TRY_TO_DECIMAL(p.AMOUNT_TEXT,12,2);
SELECT 'PDF array/error gate' AS CLAIM,1 AS EXPECTED,COUNT(*) AS ACTUAL
FROM RAW_DOCUMENTS WHERE (PAYLOAD:error IS NULL OR IS_NULL_VALUE(PAYLOAD:error))
 AND ARRAY_SIZE(PAYLOAD:response:orders:order_id)=30
 AND ARRAY_SIZE(PAYLOAD:response:orders:item)=30
 AND ARRAY_SIZE(PAYLOAD:response:orders:amount)=30;
SELECT 'HTML original provenance' AS CLAIM,0 AS EXPECTED,COUNT(*) AS ACTUAL FROM RAW_HTML
WHERE ORIGINAL_FILE IS DISTINCT FROM 'orders.html' OR SOURCE_FILE IS DISTINCT FROM 'orders.html'
 OR SOURCE_ROW IS NULL OR SOURCE_ROW NOT BETWEEN 1 AND 2000 OR LOADED_AT IS NULL
 OR SOURCE_ROW IS DISTINCT FROM TRY_TO_NUMBER(SUBSTR(ORDER_ID,2));
SELECT 'unique HTML source ordinals' AS CLAIM,2000 AS EXPECTED,
 COUNT(DISTINCT SOURCE_ROW) AS ACTUAL FROM RAW_HTML;
SELECT SOURCE_FILE,EXTRACTION_METHOD,PAYLOAD:error AS EXTRACTION_ERROR FROM RAW_DOCUMENTS;
