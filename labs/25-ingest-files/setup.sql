-- Trap: staged files are not tables; document extraction is not native COPY.
-- Destructive only to this lab database. Rerun setup resets load history too.
SET NS = (SELECT REGEXP_REPLACE(CURRENT_USER(), '[^A-Za-z0-9]', '_'));
SET WH = 'COCO_WS_WH_' || $NS;
SET SHARED_DB = 'COCO_WS_SHARED_DB_' || $NS;
SET SHARED_SCHEMA = $SHARED_DB || '.WORKSHOP';
SET RUN_LOG = $SHARED_SCHEMA || '.LAB_RUN_LOG';
SET LAB_DB = 'COCO_WS_LAB25_DB_' || $NS;
CREATE WAREHOUSE IF NOT EXISTS IDENTIFIER($WH)
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
USE WAREHOUSE IDENTIFIER($WH);
CREATE DATABASE IF NOT EXISTS IDENTIFIER($SHARED_DB);
CREATE SCHEMA IF NOT EXISTS IDENTIFIER($SHARED_SCHEMA);
CREATE TABLE IF NOT EXISTS IDENTIFIER($RUN_LOG) (
  LAB_ID VARCHAR(16), LAB_NAME VARCHAR(200), EVENT_TYPE VARCHAR(20),
  EVENT_TS TIMESTAMP_LTZ, USER_NAME VARCHAR(200), ROLE_NAME VARCHAR(200),
  WAREHOUSE_NAME VARCHAR(200), SESSION_ID VARCHAR(50), QUERY_TAG VARCHAR(200));
ALTER SESSION SET QUERY_TAG = 'COCO_WS_LAB25';
CREATE OR REPLACE DATABASE IDENTIFIER($LAB_DB);
USE DATABASE IDENTIFIER($LAB_DB);
CREATE SCHEMA LAB;
USE SCHEMA LAB;
CREATE STAGE FILES DIRECTORY = (ENABLE = TRUE) ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE');
CREATE FILE FORMAT CSV_FORMAT TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"';
CREATE FILE FORMAT JSON_FORMAT TYPE = JSON STRIP_OUTER_ARRAY = TRUE;
CREATE FILE FORMAT XML_FORMAT TYPE = XML DISABLE_AUTO_CONVERT = TRUE;
CREATE TABLE RAW_CSV (ORDER_ID VARCHAR, ITEM VARCHAR, AMOUNT_TEXT VARCHAR,
  SOURCE_FILE VARCHAR, SOURCE_ROW NUMBER, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE RAW_JSON (PAYLOAD VARIANT, SOURCE_FILE VARCHAR, SOURCE_ROW NUMBER,
  LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE RAW_XML LIKE RAW_JSON;
CREATE TABLE RAW_HTML (ORDER_ID VARCHAR, ITEM VARCHAR, AMOUNT_TEXT VARCHAR,
  ORIGINAL_FILE VARCHAR, SOURCE_FILE VARCHAR, SOURCE_ROW NUMBER,
  LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE RAW_DOCUMENTS (SOURCE_FILE VARCHAR, EXTRACTION_METHOD VARCHAR,
  PAYLOAD VARIANT, EXTRACTED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
-- Zip column arrays by index, never flatten them independently (cartesian product).
CREATE VIEW RAW_PDF_LINES AS
SELECT SOURCE_FILE, EXTRACTION_METHOD, f.INDEX AS SOURCE_ROW,
       f.VALUE::VARCHAR AS ORDER_ID,
       d.PAYLOAD:response:orders:item[f.INDEX]::VARCHAR AS ITEM,
       d.PAYLOAD:response:orders:amount[f.INDEX]::VARCHAR AS AMOUNT_TEXT
FROM RAW_DOCUMENTS d, LATERAL FLATTEN(INPUT => d.PAYLOAD:response:orders:order_id) f
WHERE d.PAYLOAD:error IS NULL OR IS_NULL_VALUE(d.PAYLOAD:error);
INSERT INTO IDENTIFIER($RUN_LOG)
SELECT 'LAB25', 'Files to raw tables', 'SETUP', CURRENT_TIMESTAMP(), CURRENT_USER(),
       CURRENT_ROLE(), CURRENT_WAREHOUSE(), CURRENT_SESSION(), CURRENT_QUERY_TAG();
SELECT $LAB_DB AS YOUR_LAB_DATABASE, $LAB_DB || '.LAB' AS YOUR_LAB_SCHEMA,
       $WH AS YOUR_WAREHOUSE, $SHARED_DB AS YOUR_SHARED_DATABASE;
